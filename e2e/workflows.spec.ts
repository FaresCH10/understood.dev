import { test, expect } from '@playwright/test';

const password='Understood-demo-2026!';
test('supervisor reviews and sends; worker acknowledges then completes independently',async({page,browser})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Work email').fill('owner@demo.understood.local');
  await page.getByLabel('Password',{exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Good to see you/})).toBeVisible();
  await page.screenshot({path:'.data/screenshots/supervisor-today.png',fullPage:true});
  const title=`Browser workflow ${Date.now()}`;
  await page.getByRole('button',{name:/New instruction/}).click();
  await page.getByLabel('Instruction title').fill(title);
  await page.getByLabel('What does your team need to do?').fill('Place the blue boxes in bay 4.');
  await page.getByLabel('Delivery format').selectOption('text');
  await page.getByLabel('Response requirement').selectOption('false');
  await page.getByRole('button',{name:/Continue/}).click();
  await page.getByLabel(/Asha/).check();
  await page.getByRole('button',{name:/Continue/}).click();
  await page.getByRole('button',{name:'Save & prepare for review',exact:true}).click();
  await expect(page.getByRole('heading',{name:title,exact:true})).toBeVisible();
  const prepare=page.getByRole('button',{name:'Prepare languages',exact:true});
  if(await prepare.isVisible())await prepare.click();
  await page.getByRole('button',{name:'Approve this version',exact:true}).click();
  await page.getByRole('button',{name:'Publish instruction',exact:true}).click();
  await expect(page.getByText(/Version 1 · published/)).toBeVisible();
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  const portal=await context.newPage();portal.on('pageerror',error=>errors.push(error.message));
  await portal.goto('http://localhost:5173/i/');
  await portal.getByLabel('Company identifier',{exact:true}).fill('understood-demo');
  await portal.getByLabel('Worker ID',{exact:true}).fill('W001');
  await portal.getByLabel('Password',{exact:true}).fill(password);
  await portal.getByRole('button',{name:/Sign in/}).click();
  await portal.getByRole('heading',{name:title,exact:true}).click();
  await expect(portal.getByText('Place the blue boxes in bay 4.',{exact:true})).toBeVisible();
  await portal.screenshot({path:'.data/screenshots/worker-instruction-mobile.png',fullPage:true});
  await portal.getByRole('button',{name:/Acknowledge receipt/}).click();
  await expect(portal.getByRole('button',{name:'Mark work complete',exact:true})).toBeVisible();
  await portal.getByRole('button',{name:'Mark work complete',exact:true}).click();
  await expect(portal.getByRole('button',{name:'Mark work complete',exact:true})).toHaveCount(0);
  const overflow=await portal.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);expect(overflow).toBe(false);
  await page.getByRole('button',{name:/Reports/}).click();
  await expect(page.getByRole('heading',{name:'By language',exact:true})).toBeVisible();
  await expect(page.getByRole('heading',{name:'By crew',exact:true})).toBeVisible();
  await expect(page.getByRole('cell',{name:'en',exact:true}).first()).toBeVisible();
  await page.screenshot({path:'.data/screenshots/reports-breakdowns.png',fullPage:true});
  expect(errors).toEqual([]);await context.close();
});

test('verification email links open the correct form and Arabic layout is RTL',async({page})=>{
  await page.goto('/signin?verify=example-verification-token-for-browser-test');
  await expect(page.getByRole('heading',{name:'Verify your email',exact:true})).toBeVisible();
  await page.goto('/signin?reset=example-recovery-token-for-browser-test');
  await expect(page.getByRole('heading',{name:'Set a new password',exact:true})).toBeVisible();
  await page.goto('/signin?invite=example-invitation-token-for-browser-test');
  await expect(page.getByRole('heading',{name:'Join your team',exact:true})).toBeVisible();
  await page.goto('/');
  await page.getByRole('button',{name:'العربية',exact:true}).click();
  await expect(page.locator('html')).toHaveAttribute('dir','rtl');
  await page.screenshot({path:'.data/screenshots/staff-arabic-signin.png',fullPage:true});
});
